export function usePRCopy() {
  const locale = useLocale();
  return {
    ...locale,
    t: (key: keyof typeof zh, params: Record<string, string | number> = {}) => {
      const english: Partial<Record<keyof typeof zh, string>> = {
        open: 'Open',
        closed: 'Closed',
        merged: 'Merged',
        all: 'All',
      };
      const text = locale.language === 'zh-CN' ? zh[key] : (english[key] ?? key);
      return text.replace(/\{(\w+)\}/g, (_, name: string) =>
        typeof params[name] === 'number'
          ? new Intl.NumberFormat(locale.language).format(params[name])
          : String(params[name] ?? `{${name}}`),
      );
    },
  };
}
